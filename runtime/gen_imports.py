#!/usr/bin/env python3
"""Generate logging stubs for every __imp__ kernel/xam symbol the recompiled
code needs, skipping the ones hand-implemented in imports_manual.cpp.

Usage: python3 gen_imports.py <out/ppc_func_mapping.cpp> [imports_manual.cpp] [<output>]
Writes imports_gen.cpp next to this script, or <output> (the 1.2 build writes it into its build folder).
"""
import os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
mapping = sys.argv[1]
manual_src = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, 'imports_manual.cpp')

# Every host symbol in the function mapping that is a named import.
needed = sorted(set(
    m for m in re.findall(r',\s*(__imp__[A-Za-z0-9_]+)', open(mapping).read())
    if not m.startswith('__imp__sub_')))

# Every hand-written imports_*.cpp beside this script (except the generated one)
# contributes to the manual set, so new files never collide with generated stubs.
import glob
manual = set()
for f in glob.glob(os.path.join(here, 'imports_*.cpp')):
    if os.path.basename(f) == 'imports_gen.cpp':
        continue
    manual |= set(re.findall(r'PPC_FUNC\((__imp__[A-Za-z0-9_]+)\)', open(f).read()))

out = ['// AUTO-GENERATED by gen_imports.py — do not edit by hand.',
       '#include "runtime.h"', '']
gen = 0
for n in needed:
    if n in manual:
        continue
    out.append(f'PPC_FUNC({n}) {{ StubLog("{n[7:]}", ctx); ctx.r3.u64 = 0; }}')
    gen += 1

open(sys.argv[3] if len(sys.argv) > 3 else os.path.join(here, 'imports_gen.cpp'), 'w').write('\n'.join(out) + '\n')
print(f"gen_imports: {len(needed)} imports total, {gen} generated stubs, {len(manual)} manual")
