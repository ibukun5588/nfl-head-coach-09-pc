#!/usr/bin/env python3
"""Generate runtime/hooks_music.cpp: entry/exit trace wrappers (HC09_TRACE_MUSIC=1)
around guest functions, for finding why front-end music never starts.

Usage: py -3.11 tools/gen_trace_hooks.py   (run from the repo root, after build.sh/build.py)

Sets traced:
- every function of sound/music/music_engine.cpp (0x82874000-0x82877000; found
  through its assert path strings) and the song manager / playlist manager /
  DB-query functions that reference its strings;
- every method of the vtable at 0x820AC8C0 (111 entries) of the global object at
  0x8313BB28 (static initializer sub_82F75830): init/shutdown pairs of game
  subsystems; entry 74 (sub_827C4048) creates the MusicPlaylistMgr singleton.
Each wrapper logs the first 6 calls, then powers of two: thread, swap, r3-r6, return.
"""
import re, struct

mapping = open('out/ppc_func_mapping.cpp').read()
funcs = set(int(a, 16) for a in re.findall(r'\{ 0x([0-9A-F]{8}), sub_', mapping))
image = open('headcoach.basefile', 'rb').read()
BASE = 0x82000000

traced = {a for a in funcs if 0x82874000 <= a < 0x82877000}
traced |= {0x8283AE48, 0x8285BA68, 0x82841F80, 0x82841EB8, 0x82871300, 0x827F82C0}
# Front-end music start: script FrontEndAdapterClass.FrontEndStarted (thunk sub_82CC5090 -> adapter slot 8
# sub_827A9918) posts message 155; the engine's handler sub_82867770 then plays the menu playlist
# (sub_8285BA68 -> sub_8285B978/B388). SetAllowStartPodcast = sub_82CC50F8 -> sub_827A9968.
traced |= {0x82CC5090, 0x82CC50F8, 0x827A9918, 0x827A9968, 0x82867770, 0x8285B978, 0x8285B388, 0x8285B558,
           0x8285B670, 0x827FD1F0, 0x827FD128}
# Every function that reads the music engine instance (global at 0x831D8AD4): its clients.
traced |= {0x8237A670, 0x8237D4B0, 0x823B37C0, 0x823D4208, 0x825BE9B8, 0x825DE1A8, 0x825DE218, 0x8266E4A0,
           0x8266E660, 0x82797448, 0x82797500, 0x82797AC0, 0x827A27B0, 0x827A28F0, 0x827FD128, 0x827FD1F0,
           0x827FD3D0, 0x827FD610, 0x827FD7A8, 0x827FDBC8, 0x827FDDB8, 0x827FDF48, 0x82807860, 0x8283ADF8,
           0x82856FC8, 0x82859798, 0x8285BE98, 0x82864578, 0x82865FB0, 0x828661E0, 0x828707E0}
VT, VT_N = 0x820AC8C0, 111
SHARED = {0x8279F208, 0x8268BFE8}   # stubs shared by many classes: too noisy
for i in range(VT_N):
    a = struct.unpack('>I', image[VT - BASE + 4 * i: VT - BASE + 4 * i + 4])[0]
    if a in funcs and a not in SHARED:
        traced.add(a)

out = [
    '// AUTO-GENERATED by tools/gen_trace_hooks.py — diagnostic (HC09_TRACE_MUSIC=1).',
    '// Entry/exit of the music engine\'s functions and of the methods of the subsystem',
    '// object at 0x8313BB28 (vtable 0x820AC8C0); first calls of each.',
    '#include "kernel.h"', '#include "gpu.h"', '',
    '#include <cstdlib>', '#include <mutex>', '#include <unordered_map>', '',
    'namespace {',
    'bool MusicTraceOn() { static const bool on = getenv("HC09_TRACE_MUSIC") != nullptr; return on; }',
    'struct FnTrace',
    '{',
    '    uint32_t addr; uint64_t n = 0; bool log = false;',
    '    FnTrace(uint32_t a, PPCContext& ctx) : addr(a)',
    '    {',
    '        if (!MusicTraceOn()) return;',
    '        static std::mutex mu; static std::unordered_map<uint32_t, uint64_t> calls;',
    '        { std::lock_guard<std::mutex> lk(mu); n = ++calls[a]; }',
    '        log = n <= 6 || (n & (n - 1)) == 0;',
    '        // Message handlers (r4 = message): the first 400 calls, with the 16-bit type at +8.',
    '        bool msg = a == 0x82875180 || a == 0x82875AB8 || a == 0x82867770;',
    '        if (msg) log = n <= 400;',
    '        int type = msg && ctx.r4.u32 >= 0x40000000u ? GLoad16(ctx.r4.u32 + 8) : -1;',
    '        // The front-end music controller\'s gate (sub_82807860): r3 -> 4 flag bytes; start needs [1],[2],[3].',
    '        if (a == 0x82807860 && ctx.r3.u32 >= 0x40000000u) type = int(GLoad32(ctx.r3.u32));',
    '        if (log) fprintf(stderr, "[music] t%llu sw%llu > sub_%08X #%llu r3=%08X r4=%08X r5=%08X r6=%08X lr=%08X type %d\\n",',
    '                         (unsigned long long)KernelCurrentTid(), (unsigned long long)GpuSwapCount(), a, (unsigned long long)n,',
    '                         ctx.r3.u32, ctx.r4.u32, ctx.r5.u32, ctx.r6.u32, uint32_t(ctx.lr), type);',
    '    }',
    '    void Leave(PPCContext& ctx)',
    '    {',
    '        if (log) fprintf(stderr, "[music] t%llu < sub_%08X #%llu -> r3=%08X\\n", (unsigned long long)KernelCurrentTid(), addr,',
    '                         (unsigned long long)n, ctx.r3.u32);',
    '    }',
    '};',
    '}  // namespace', '',
]
for a in sorted(traced):
    h = '%08X' % a
    out.append(f'extern "C" PPC_FUNC(__imp__sub_{h});')
    out.append(f'PPC_FUNC(sub_{h}) {{ FnTrace t(0x{h}, ctx); __imp__sub_{h}(ctx, base); t.Leave(ctx); }}')
open('runtime/hooks_music.cpp', 'w', newline='\n').write('\n'.join(out) + '\n')
print(f'gen_trace_hooks: {len(traced)} functions')
