#!/usr/bin/env python3
"""List a XEX2's import table and emit a C++ table of the *variable* imports.

XenonRecomp turns function imports into __imp__ thunks, but the kernel's
exported *variables* (VdGlobalDevice, XboxHardwareInfo, KeTimeStampBundle, ...)
are imported differently: the game reads the import slot in the image header
and expects the kernel to have written the variable's address there. This tool
finds those slots so the runtime can patch them at load.

Usage: python3 xeximports.py default.xex out/xex_imports.cpp
"""
import struct, sys

XEX_HEADER_IMPORT_LIBRARIES = 0x000103FF

def main(inp, outp):
    data = open(inp, 'rb').read()
    u32 = lambda o: struct.unpack('>I', data[o:o+4])[0]
    u16 = lambda o: struct.unpack('>H', data[o:o+2])[0]
    assert data[:4] == b'XEX2', "not a XEX2 file"
    opt = {}
    for i in range(u32(0x14)):
        off = 0x18 + i*8
        opt[u32(off)] = u32(off+4)
    imp = opt[XEX_HEADER_IMPORT_LIBRARIES]
    size_hdr, size_str, num = u32(imp), u32(imp+4), u32(imp+8)
    # string table
    names, p = [], imp + 12
    for _ in range(num):
        e = data.index(b'\0', p)
        names.append(data[p:e].decode())
        p += ((e - p + 1) + 3) & ~3
    lib = imp + 12 + size_str
    rows = []   # (slot VA, lib, ordinal, type)
    for li in range(num):
        lsize = u32(lib)
        nimports = u16(lib + 0x24 + 2)
        desc = lib + 0x28
        for k in range(nimports):
            # Need the slot's *content* (type/ordinal) — it lives in the PE
            # image, not the XEX header. The caller patches using the basefile,
            # so here we only record the slot address; the runtime reads the
            # ordinal/type from the slot itself.
            rows.append((u32(desc + 4*k), li))
        lib += lsize
    with open(outp, 'w') as f:
        f.write('// Generated by tools/xeximports.py — XEX import slots (see runtime/xex_imports.h)\n')
        f.write('#include <cstdint>\n#include "xex_imports.h"\n')
        f.write('const char* const g_xexImportLibs[] = { %s };\n' % ', '.join('"%s"' % n for n in names))
        f.write('const uint32_t g_xexImportLibCount = %d;\n' % len(names))
        f.write('const XexImportSlot g_xexImportSlots[] = {\n')
        for va, li in rows:
            f.write('    { 0x%08X, %d },\n' % (va, li))
        f.write('};\nconst uint32_t g_xexImportSlotCount = %d;\n' % len(rows))
    print(f"OK: {len(names)} libraries ({', '.join(names)}), {len(rows)} import slots -> {outp}")

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
