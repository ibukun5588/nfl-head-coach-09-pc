#!/usr/bin/env python3
"""Generate runtime/hooks_sim.cpp: call-counting wrappers (HC09_TRACE_SIM=1) around the
game's simulation code, for finding how a simmed game decides its plays.

Usage: py -3.11 tools/gen_sim_hooks.py   (run from the repo root, after build.sh/build.py)

Ranges (from the SuperSim strings): 0x82955000-0x82978000 the SuperSim engine (SimPlay,
FastSimState, SimRandom, CompoundAbilityMgr, ...), 0x826E0000-0x82700000 GameSimMgr /
SimEngine / the SuperSim game states, 0x826A0000-0x826A8000 GameSimData. Functions already
wrapped by another hooks_*.cpp are skipped (one strong definition per symbol).

Output: the first call of each function (swap, r3-r6, caller), and every 5 s a report of
the 40 busiest functions since the previous report.
"""
import glob, re

mapping = open('out/ppc_func_mapping.cpp').read()
funcs = sorted(int(a, 16) for a in re.findall(r'\{ 0x([0-9A-F]{8}), sub_', mapping))
RANGES = [(0x82955000, 0x82978000), (0x826E0000, 0x82700000), (0x826A0000, 0x826A8000)]
taken = set()
for f in glob.glob('runtime/hooks_*.cpp'):
    if f.replace('\\', '/').endswith('hooks_sim.cpp'):
        continue
    taken |= {int(a, 16) for a in re.findall(r'PPC_FUNC\(sub_([0-9A-F]{8})\)', open(f, encoding='utf-8', errors='replace').read())}
traced = [a for a in funcs if any(lo <= a < hi for lo, hi in RANGES) and a not in taken]

out = [
    '// AUTO-GENERATED by tools/gen_sim_hooks.py — diagnostic (HC09_TRACE_SIM=1).',
    '// Call counts of the game\'s simulation code (SuperSim engine, GameSimMgr, GameSimData).',
    '#include "kernel.h"', '#include "gpu.h"', '',
    '#include <algorithm>', '#include <atomic>', '#include <chrono>', '#include <cstdio>',
    '#include <cstdlib>', '#include <mutex>', '#include <thread>', '#include <vector>', '',
    'namespace {',
    f'constexpr int kCount = {len(traced)};',
    'const uint32_t kAddr[kCount] = {',
]
for i in range(0, len(traced), 8):
    out.append('    ' + ', '.join('0x%08X' % a for a in traced[i:i + 8]) + ',')
out += [
    '};',
    'std::atomic<uint64_t> g_calls[kCount];',
    'bool SimTraceOn() { static const bool on = getenv("HC09_TRACE_SIM") != nullptr; return on; }',
    'void Reporter()',
    '{',
    '    std::vector<uint64_t> last(kCount, 0);',
    '    for (;;) {',
    '        std::this_thread::sleep_for(std::chrono::seconds(5));',
    '        std::vector<std::pair<uint64_t, int>> d;',
    '        for (int i = 0; i < kCount; ++i) {',
    '            uint64_t c = g_calls[i].load(std::memory_order_relaxed);',
    '            if (c != last[i]) d.push_back({c - last[i], i});',
    '            last[i] = c;',
    '        }',
    '        if (d.empty()) continue;',
    '        std::sort(d.rbegin(), d.rend());',
    '        fprintf(stderr, "[sim] report sw%llu: %zu functions active\\n", (unsigned long long)GpuSwapCount(), d.size());',
    '        for (size_t k = 0; k < d.size() && k < 40; ++k)',
    '            fprintf(stderr, "[sim]   sub_%08X %llu\\n", kAddr[d[k].second], (unsigned long long)d[k].first);',
    '    }',
    '}',
    'inline void Count(int i, PPCContext& ctx)',
    '{',
    '    if (!SimTraceOn()) return;',
    '    static std::once_flag once;',
    '    std::call_once(once, [] { std::thread(Reporter).detach(); });',
    '    if (g_calls[i].fetch_add(1, std::memory_order_relaxed) == 0)',
    '        fprintf(stderr, "[sim] first sub_%08X sw%llu t%llu r3=%08X r4=%08X r5=%08X r6=%08X lr=%08X\\n", kAddr[i],',
    '                (unsigned long long)GpuSwapCount(), (unsigned long long)KernelCurrentTid(),',
    '                ctx.r3.u32, ctx.r4.u32, ctx.r5.u32, ctx.r6.u32, uint32_t(ctx.lr));',
    '}',
    '}  // namespace', '',
]
for i, a in enumerate(traced):
    h = '%08X' % a
    out.append(f'extern "C" PPC_FUNC(__imp__sub_{h});')
    out.append(f'PPC_FUNC(sub_{h}) {{ Count({i}, ctx); __imp__sub_{h}(ctx, base); }}')
open('runtime/hooks_sim.cpp', 'w', newline='\n').write('\n'.join(out) + '\n')
print(f'gen_sim_hooks: {len(traced)} functions')
