// The patched game for Play: <version>-patched\hc09.exe, rebuilt by hc09-build when the patches that are on (or the
// kit) changed since the last build (patches.key), and its image: the version's headcoach.basefile with the same
// writes. False when a build was started (Play runs again when it is done) or something failed (shown to the player).
bool PreparePatched(const Version& v, const std::wstring& root, std::wstring& exe, std::wstring& imageRel)
{
    std::string writes = XeniaWritesText(PatchesOn(v.name));
    std::wstring sub = Widen(v.name) + L"-patched", pdir = g.dir + L"\\" + sub, kit = g.dir + L"\\kit";
    if (!FileExists(kit + L"\\hc09-build.exe"))
    {
        MessageBoxW(g.wnd, L"Patches need the installed game: the kit folder (the build tools setup installs) is missing here.",
                    L"HC09", MB_ICONERROR);
        return false;
    }
    std::vector<uint8_t> kitIni, rt;
    ReadFile(kit + L"\\kit.ini", kitIni);
    ReadFile(kit + L"\\rt\\" + Widen(v.name) + L"\\hc09rt.dll", rt);
    std::string keyText = writes + "\n" + std::string(kitIni.begin(), kitIni.end()) + "\n" + Sha256Hex(rt.data(), rt.size());
    std::string key = Sha256Hex(reinterpret_cast<const uint8_t*>(keyText.data()), keyText.size());
    std::vector<uint8_t> stamp;
    ReadFile(pdir + L"\\patches.key", stamp);
    if (!FileExists(pdir + L"\\hc09.exe") || std::string(stamp.begin(), stamp.end()) != key)
    {
        std::error_code ec;
        std::filesystem::create_directories(pdir, ec);
        DeleteFileW((pdir + L"\\patches.key").c_str());
        if (!WriteFile(pdir + L"\\patches.txt", writes.data(), writes.size()))
        {
            MessageBoxW(g.wnd, (L"Could not write " + pdir + L"\\patches.txt.").c_str(), L"HC09", MB_ICONERROR);
            return false;
        }
        std::vector<std::wstring> args{ kit + L"\\hc09-build.exe", L"--kit", kit, L"--version", Widen(v.name), L"--xex",
                                        root + L"\\default.xex", L"--dest", pdir, L"--work", g.dir + L"\\build-work-patched",
                                        L"--patches", pdir + L"\\patches.txt" };
        if (IsV12(v)) { args.push_back(L"--tu"); args.push_back(GetText(kTu)); }
        std::wstring cmd;
        for (const std::wstring& a : args) cmd += (cmd.empty() ? L"" : L" ") + (L"\"" + a + L"\"");
        g.patchBuilding = true;
        EnableWindow(g.Ctl(kPlay), FALSE);
        SetStatus(L"Building game version " + Widen(v.name) + L" with your patches (a few minutes, once)...");
        HWND w = g.wnd;
        std::wstring keyFile = pdir + L"\\patches.key";
        std::thread([w, cmd, keyFile, key] {
            SECURITY_ATTRIBUTES sa{ sizeof(sa), nullptr, TRUE };
            HANDLE rd = nullptr, wr = nullptr;
            CreatePipe(&rd, &wr, &sa, 0);
            SetHandleInformation(rd, HANDLE_FLAG_INHERIT, 0);
            STARTUPINFOW si{ sizeof(si) };
            si.dwFlags = STARTF_USESTDHANDLES;
            si.hStdOutput = si.hStdError = wr;
            PROCESS_INFORMATION pi{};
            std::wstring c = cmd;
            DWORD code = 1;
            if (CreateProcessW(nullptr, c.data(), nullptr, nullptr, TRUE, CREATE_NO_WINDOW, nullptr, nullptr, &si, &pi))
            {
                CloseHandle(wr);
                wr = nullptr;
                std::string line;
                char buf[4096];
                DWORD got = 0;
                while (::ReadFile(rd, buf, sizeof buf, &got, nullptr) && got)
                    for (DWORD i = 0; i < got; ++i)
                    {
                        if (buf[i] == '\r') continue;
                        if (buf[i] != '\n') { line += buf[i]; continue; }
                        unsigned done = 0, total = 0;
                        std::wstring s;
                        if (sscanf(line.c_str(), "compiled %u of %u", &done, &total) == 2 && total)
                            s = L"Building with your patches: compiling " + std::to_wstring(done * 100 / total) + L"%...";
                        else if (line.rfind("progress ", 0) == 0 && line.find(' ', 9) != std::string::npos)
                        {
                            size_t at = line.find(' ', line.find(' ', 9) + 1);
                            if (at != std::string::npos) s = L"Building with your patches: " + Widen(line.substr(at + 1)) + L"...";
                        }
                        else if (line.rfind("FAILED", 0) == 0 || line.find("failed") != std::string::npos) s = Widen(line);
                        if (!s.empty()) PostMessageW(w, kPatchBuildLine, 0, LPARAM(new std::wstring(s)));
                        line.clear();
                    }
                WaitForSingleObject(pi.hProcess, INFINITE);
                GetExitCodeProcess(pi.hProcess, &code);
                CloseHandle(pi.hProcess);
                CloseHandle(pi.hThread);
                if (code == 0 && !WriteFile(keyFile, key.data(), key.size())) code = 1;
            }
            if (wr) CloseHandle(wr);
            CloseHandle(rd);
            PostMessageW(w, kPatchBuildDone, WPARAM(code), 0);
        }).detach();
        return false;
    }
    std::vector<uint8_t> image;
    std::string err;
    if (!ReadFile(VerDir(v) + L"\\headcoach.basefile", image) || !ApplyXeniaWrites(writes, image, 0x82000000, err) ||
        !WriteFile(pdir + L"\\headcoach.basefile", image.data(), image.size()))
    {
        MessageBoxW(g.wnd, (L"Could not make the patched game image" + (err.empty() ? L"." : L": " + Widen(err))).c_str(), L"HC09", MB_ICONERROR);
        return false;
    }
    exe = pdir + L"\\hc09.exe";
    imageRel = sub + L"\\headcoach.basefile";
    return true;
}

