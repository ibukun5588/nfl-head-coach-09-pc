// Keeps the file's other lines and comments; sets `key = value` in [section] (added when missing).
struct Ini
{
    std::vector<std::string> lines;
    bool Load(const std::wstring& path)
    {
        std::vector<uint8_t> b;
        lines.clear();
        if (!ReadFile(path, b)) return false;
        std::string s(b.begin(), b.end()), cur;
        for (char c : s)
        {
            if (c == '\n') { if (!cur.empty() && cur.back() == '\r') cur.pop_back(); lines.push_back(cur); cur.clear(); }
            else cur += c;
        }
        if (!cur.empty()) lines.push_back(cur);
        return true;
    }
    bool Save(const std::wstring& path) const
    {
        std::string s;
        for (const std::string& l : lines) { s += l; s += "\r\n"; }
        return WriteFile(path, s.data(), s.size());
    }
    // [first, last) lines of the section's body; first = index of its header, or -1
    void Find(const std::string& section, int& header, int& end) const
    {
        header = -1;
        end = int(lines.size());
        for (int i = 0; i < int(lines.size()); ++i)
        {
            std::string t = Trim(lines[size_t(i)]);
            if (t.size() > 1 && t[0] == '[')
            {
                if (header >= 0) { end = i; return; }
                if (Lower(t) == "[" + section + "]") header = i;
            }
        }
    }
    int KeyLine(const std::string& section, const std::string& key) const
    {
        int h, e;
        Find(section, h, e);
        if (h < 0) return -1;
        for (int i = h + 1; i < e; ++i)
        {
            std::string t = Trim(lines[size_t(i)]);
            if (t.empty() || t[0] == ';' || t[0] == '#') continue;
            size_t eq = t.find('=');
            if (eq != std::string::npos && Lower(Trim(t.substr(0, eq))) == key) return i;
        }
        return -1;
    }
    std::string Get(const std::string& section, const std::string& key, const std::string& def = "") const
    {
        int i = KeyLine(section, key);
        if (i < 0) return def;
        const std::string& l = lines[size_t(i)];
        std::string v = Trim(l.substr(l.find('=') + 1));
        return v.empty() ? def : v;
    }
    void Set(const std::string& section, const std::string& key, const std::string& value)
    {
        int i = KeyLine(section, key);
        if (i >= 0) { lines[size_t(i)] = key + " = " + value; return; }
        int h, e;
        Find(section, h, e);
        if (h < 0)
        {
            if (!lines.empty() && !Trim(lines.back()).empty()) lines.push_back("");
            lines.push_back("[" + section + "]");
            lines.push_back(key + " = " + value);
            return;
        }
        int at = e;
        while (at > h + 1 && Trim(lines[size_t(at - 1)]).empty()) --at;   // before the blank lines that end the section
        lines.insert(lines.begin() + at, key + " = " + value);
    }
};

