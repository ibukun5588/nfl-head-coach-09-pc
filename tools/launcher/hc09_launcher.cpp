bool FileExists(const std::wstring& p, uint64_t* size = nullptr)
{
    WIN32_FILE_ATTRIBUTE_DATA a;
    if (!GetFileAttributesExW(p.c_str(), GetFileExInfoStandard, &a) || (a.dwFileAttributes & FILE_ATTRIBUTE_DIRECTORY)) return false;
    if (size) *size = (uint64_t(a.nFileSizeHigh) << 32) | a.nFileSizeLow;
    return true;
}
bool ReadFile(const std::wstring& p, std::vector<uint8_t>& out)
{
    HANDLE h = CreateFileW(p.c_str(), GENERIC_READ, FILE_SHARE_READ, nullptr, OPEN_EXISTING, 0, nullptr);
    if (h == INVALID_HANDLE_VALUE) return false;
    LARGE_INTEGER sz;
    bool ok = GetFileSizeEx(h, &sz) && sz.QuadPart < (1ll << 31);
    if (ok)
    {
        out.resize(size_t(sz.QuadPart));
        DWORD got = 0;
        ok = ::ReadFile(h, out.data(), DWORD(out.size()), &got, nullptr) && got == out.size();
    }
    CloseHandle(h);
    return ok;
}
bool WriteFile(const std::wstring& p, const void* data, size_t n)
{
    HANDLE h = CreateFileW(p.c_str(), GENERIC_WRITE, 0, nullptr, CREATE_ALWAYS, 0, nullptr);
    if (h == INVALID_HANDLE_VALUE) return false;
    DWORD put = 0;
    bool ok = ::WriteFile(h, data, DWORD(n), &put, nullptr) && put == n;
    CloseHandle(h);
    return ok;
}

// ---- crypto (Windows CNG) -------------------------------------------------------------------------------------------
std::string Sha256Hex(const uint8_t* p, size_t n)
{
    BCRYPT_ALG_HANDLE alg = nullptr;
    uint8_t h[32] = {};
    if (BCryptOpenAlgorithmProvider(&alg, BCRYPT_SHA256_ALGORITHM, nullptr, 0) != 0) return {};
    BCRYPT_HASH_HANDLE hh = nullptr;
    if (BCryptCreateHash(alg, &hh, nullptr, 0, nullptr, 0, 0) == 0)
    {
        while (n)
        {
            ULONG chunk = ULONG(std::min<size_t>(n, 1u << 30));
            BCryptHashData(hh, const_cast<PUCHAR>(p), chunk, 0);
            p += chunk;
            n -= chunk;
        }
        BCryptFinishHash(hh, h, 32, 0);
        BCryptDestroyHash(hh);
    }
    BCryptCloseAlgorithmProvider(alg, 0);
    static const char* hex = "0123456789ABCDEF";
    std::string s;
    for (uint8_t b : h) { s += hex[b >> 4]; s += hex[b & 15]; }
    return s;
}
// AES-128 decrypt in place: ECB (no IV) or CBC (IV of zeros); n a multiple of 16.
bool Aes(const uint8_t key[16], bool cbc, uint8_t* data, size_t n)
{
    BCRYPT_ALG_HANDLE alg = nullptr;
    if (BCryptOpenAlgorithmProvider(&alg, BCRYPT_AES_ALGORITHM, nullptr, 0) != 0) return false;
    const wchar_t* mode = cbc ? BCRYPT_CHAIN_MODE_CBC : BCRYPT_CHAIN_MODE_ECB;
    bool ok = BCryptSetProperty(alg, BCRYPT_CHAINING_MODE, (PUCHAR)mode, ULONG((wcslen(mode) + 1) * sizeof(wchar_t)), 0) == 0;
    BCRYPT_KEY_HANDLE k = nullptr;
    ok = ok && BCryptGenerateSymmetricKey(alg, &k, nullptr, 0, const_cast<PUCHAR>(key), 16, 0) == 0;
    if (ok)
    {
        uint8_t iv[16] = {};
        ULONG got = 0;
        ok = BCryptDecrypt(k, data, ULONG(n), nullptr, cbc ? iv : nullptr, cbc ? 16 : 0, data, ULONG(n), &got, 0) == 0 && got == n;
        BCryptDestroyKey(k);
    }
    BCryptCloseAlgorithmProvider(alg, 0);
    return ok;
}

// A retail XEX2 with BASIC compression -> its PE image (as tools/xexdec.py).
bool XexToImage(const std::vector<uint8_t>& x, std::vector<uint8_t>& out, std::string& err)
{
    auto u32 = [&](size_t o) -> uint32_t {
        return o + 4 <= x.size() ? (uint32_t(x[o]) << 24) | (uint32_t(x[o + 1]) << 16) | (uint32_t(x[o + 2]) << 8) | x[o + 3] : 0;
    };
    if (x.size() < 0x200 || memcmp(x.data(), "XEX2", 4)) { err = "default.xex is not an Xbox 360 executable (XEX2)."; return false; }
    uint32_t peOff = u32(0x08), sec = u32(0x10), nOpt = u32(0x14), ff = 0;
    for (uint32_t i = 0; i < nOpt; ++i)
        if (u32(0x18 + i * 8) == 0x000003FF) ff = u32(0x18 + i * 8 + 4);
    if (!ff || sec + 0x160 > x.size() || peOff >= x.size()) { err = "default.xex: unexpected header."; return false; }
    uint32_t imageSize = u32(sec + 0x04);
    static const uint8_t kRetailKey[16] = { 0x20, 0xB1, 0x85, 0xA5, 0x9D, 0x28, 0xFD, 0xC3, 0x40, 0x58, 0x3F, 0xBB, 0x08, 0x96, 0xBF, 0x91 };
    uint8_t session[16];
    memcpy(session, &x[sec + 0x150], 16);
    if (!Aes(kRetailKey, false, session, 16)) { err = "AES (title key) failed."; return false; }
    if (((x[ff + 6] << 8) | x[ff + 7]) != 1) { err = "default.xex: compression other than BASIC is not supported."; return false; }
    std::vector<std::pair<uint32_t, uint32_t>> blocks;
    for (uint32_t i = 0, p = ff + 8; i < (u32(ff) - 8) / 8; ++i, p += 8) blocks.push_back({ u32(p), u32(p + 4) });
    std::vector<uint8_t> dec(x.begin() + peOff, x.begin() + peOff + ((x.size() - peOff) / 16) * 16);
    if (!Aes(session, true, dec.data(), dec.size())) { err = "AES (image) failed."; return false; }
    out.clear();
    out.reserve(imageSize);
    size_t src = 0;
    for (auto [ds, zs] : blocks)
    {
        if (src + ds > dec.size()) { err = "default.xex: block table runs past the data."; return false; }
        out.insert(out.end(), dec.begin() + src, dec.begin() + src + ds);
        out.insert(out.end(), zs, 0);
        src += ds;
    }
    if (out.size() != imageSize || out.size() < 2 || out[0] != 'M' || out[1] != 'Z') { err = "default.xex: the image did not reconstruct."; return false; }
    return true;
}

