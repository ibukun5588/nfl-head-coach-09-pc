std::wstring PickFolder(const wchar_t* title, const std::wstring& start)
{
    std::wstring r;
    IFileOpenDialog* d = nullptr;
    if (FAILED(CoCreateInstance(CLSID_FileOpenDialog, nullptr, CLSCTX_INPROC_SERVER, IID_PPV_ARGS(&d)))) return r;
    DWORD opt = 0;
    d->GetOptions(&opt);
    d->SetOptions(opt | FOS_PICKFOLDERS | FOS_PATHMUSTEXIST);
    d->SetTitle(title);
    IShellItem* at = nullptr;
    if (!start.empty() && SUCCEEDED(SHCreateItemFromParsingName(start.c_str(), nullptr, IID_PPV_ARGS(&at)))) { d->SetFolder(at); at->Release(); }
    if (SUCCEEDED(d->Show(g.wnd)))
    {
        IShellItem* it = nullptr;
        if (SUCCEEDED(d->GetResult(&it)))
        {
            PWSTR p = nullptr;
            if (SUCCEEDED(it->GetDisplayName(SIGDN_FILESYSPATH, &p))) { r = p; CoTaskMemFree(p); }
            it->Release();
        }
    }
    d->Release();
    return r;
}
