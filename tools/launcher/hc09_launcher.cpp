// The game folder: what is there and what is missing (one line per problem).
bool CheckFiles(const std::wstring& root, std::wstring& msg)
{
    msg.clear();
    if (root.empty()) { msg = L"Choose the folder with your copy of the game (default.xex and the qkl_*.ast files)."; return false; }
    std::vector<std::wstring> missing;
    if (!FileExists(root + L"\\default.xex")) missing.push_back(L"default.xex");
    for (const char* a : kArchives)
        if (!FileExists(root + L"\\" + Widen(a))) missing.push_back(Widen(a));
    if (missing.empty()) { msg = L"Game files found: default.xex and the five qkl_*.ast archives."; return true; }
    msg = L"Missing in this folder:";
    for (auto& m : missing) msg += L" " + m;
    return false;
}
