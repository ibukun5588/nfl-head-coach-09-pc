// ---- the Patches tab: Xenia game patches (xenia_patch.h; 2026-10-23) ---------------------------------------------------
// Players drop Xenia .patch.toml files into <this folder>\patches. Each file is for one game version (1.2 unless the
// player picks 1.0: Xenia's hash cannot tell us). hc09.ini [patches] keeps the choices: "<file>|<n> = on/off" (the
// file's is_enabled until changed) and "<file>|version". While patches are on, only their game version can be played
// (the Game tab's version is locked). Play rebuilds that version with them once (hc09-build --patches, into
// <version>-patched\) and starts it with the patched game image.
std::wstring PatchDir() { return g.dir + L"\\patches"; }
std::string PatchKey(const XeniaPatchFile& f, const std::string& what) { return Lower(Narrow(f.fileName)) + "|" + what; }
bool PatchOn(size_t fi, size_t pi)
{
    const XeniaPatchFile& f = g.patchFiles[fi];
    if (!f.error.empty()) return false;
    std::string v = g.ini.Get("patches", PatchKey(f, std::to_string(pi)));
    return v.empty() ? f.patches[pi].enabled : OnOff(v, true);
}
std::string PatchFileVersion(size_t fi)
{
    return g.ini.Get("patches", PatchKey(g.patchFiles[fi], "version"), "1.2") == "1.0" ? "1.0" : "1.2";
}
void LoadPatches()
{
    g.patchFiles.clear();
    std::error_code ec;
    std::vector<std::wstring> paths;
    for (const auto& e : std::filesystem::directory_iterator(PatchDir(), ec))
    {
        std::wstring n = e.path().filename().wstring();
        if (e.is_regular_file() && n.size() > 5 && _wcsicmp(n.c_str() + n.size() - 5, L".toml") == 0) paths.push_back(e.path().wstring());
    }
    std::sort(paths.begin(), paths.end());
    for (const std::wstring& p : paths)
    {
        XeniaPatchFile f;
        LoadXeniaPatchFile(p, f);
        g.patchFiles.push_back(std::move(f));
    }
}
// The game version the patches that are on are for ("" when none); mixed: some for 1.0 and some for 1.2.
std::string PatchVersionOn(bool& mixed)
{
    std::string version;
    mixed = false;
    for (size_t fi = 0; fi < g.patchFiles.size(); ++fi)
        for (size_t pi = 0; pi < g.patchFiles[fi].patches.size(); ++pi)
            if (PatchOn(fi, pi))
            {
                std::string v = PatchFileVersion(fi);
                if (!version.empty() && v != version) mixed = true;
                version = v;
            }
    return version;
}
std::vector<std::pair<const XeniaPatchFile*, const XeniaPatch*>> PatchesOn(const std::string& version)
{
    std::vector<std::pair<const XeniaPatchFile*, const XeniaPatch*>> on;
    for (size_t fi = 0; fi < g.patchFiles.size(); ++fi)
        if (PatchFileVersion(fi) == version)
            for (size_t pi = 0; pi < g.patchFiles[fi].patches.size(); ++pi)
                if (PatchOn(fi, pi)) on.push_back({ &g.patchFiles[fi], &g.patchFiles[fi].patches[pi] });
    return on;
}
// The places our own code hooks into the game (the kit's recompiler config, [[midasm_hook]] addresses) that the
// patches that are on overwrite: a patch there may not work as it does in Xenia.
std::vector<uint32_t> PatchHookConflicts(const std::string& version)
{
    std::vector<uint8_t> b;
    std::vector<uint32_t> hooks, hit;
    if (!ReadFile(g.dir + L"\\kit\\config\\" + Widen(version) + L"\\hc09.toml", b)) return hit;
    std::string s(b.begin(), b.end());
    for (size_t at = s.find("[[midasm_hook]]"); at != std::string::npos; at = s.find("[[midasm_hook]]", at + 1))
    {
        size_t a = s.find("address", at), next = s.find("[[", at + 2);
        if (a != std::string::npos && (next == std::string::npos || a < next))
        {
            size_t x = s.find("0x", a);
            if (x != std::string::npos) hooks.push_back(uint32_t(strtoul(s.c_str() + x, nullptr, 16)));
        }
    }
    for (const auto& [f, p] : PatchesOn(version))
        for (const XeniaWrite& w : p->writes)
            for (uint32_t h : hooks)
                if (h + 4 > w.address && h < w.address + w.bytes.size() && std::find(hit.begin(), hit.end(), h) == hit.end())
                    hit.push_back(h);
    return hit;
}
// The Game tab's version is locked to the patches' version while patches are on.
void UpdatePatchLock()
{
    bool mixed = false;
    std::string v = PatchVersionOn(mixed);
    std::wstring note;
    int locked = -1;
    if (mixed)
        note = L"Patches for both 1.0 and 1.2 are on (Patches tab): turn off one set to play.";
    else if (!v.empty())
    {
        for (size_t i = 0; i < g.versions.size(); ++i)
            if (v == g.versions[i].name) locked = int(i);
        note = locked >= 0 ? L"Patches are on for game version " + Widen(v) + L": the other version can be played again "
                             L"once they are turned off (Patches tab)."
                           : L"Patches are on for game version " + Widen(v) + L", which is not installed here.";
    }
    if (locked >= 0) Select(kVersion, locked);
    EnableWindow(g.Ctl(kVersion), locked < 0 && g.versions.size() > 1);
    SetWindowTextW(g.Ctl(kPatchLock), note.c_str());
}
