#!/usr/bin/env python3
"""Generate runtime/overlay_font.h: a small bitmap font (ASCII 32-126) for the in-game overlay.

Rendered from Pillow's built-in default font (Aileron, CC0 / public domain) at a fixed pixel size, thresholded to
1 bit. Each glyph: an advance width and kH rows of bits (bit 0 = leftmost pixel).

    py -3.11 tools/gen_overlay_font.py
"""
import os
from PIL import Image, ImageDraw, ImageFont

SIZE = 13
font = ImageFont.load_default(size=SIZE)
asc, desc = font.getmetrics()
H = asc + desc
rows_all, widths = [], []
for c in range(32, 127):
    ch = chr(c)
    w = max(1, int(round(font.getlength(ch))))
    img = Image.new('L', (w + 4, H), 0)
    ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255)
    px = img.load()
    rows = []
    for y in range(H):
        bits = 0
        for x in range(min(w + 4, 32)):
            if px[x, y] >= 110:
                bits |= 1 << x
        rows.append(bits)
    rows_all.append(rows)
    widths.append(w)

out = ['// AUTO-GENERATED by tools/gen_overlay_font.py: bitmap of Pillow\'s default font (Aileron, CC0), size %d.' % SIZE,
       '// ASCII 32-126; each glyph: advance width (px) and kOvFontH rows, bit 0 = leftmost pixel.',
       '#pragma once', '#include <cstdint>', '',
       'constexpr int kOvFontH = %d;' % H,
       'constexpr uint8_t kOvFontW[95] = {' + ', '.join(map(str, widths)) + '};',
       'constexpr uint32_t kOvFontRows[95][%d] = {' % H]
for c, rows in zip(range(32, 127), rows_all):
    out.append('    {' + ', '.join('0x%X' % r for r in rows) + '},   // %r' % chr(c))
out.append('};')
dst = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'runtime', 'overlay_font.h')
open(dst, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('wrote', dst, 'height', H)
