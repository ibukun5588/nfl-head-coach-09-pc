#!/usr/bin/env python3
"""Generate runtime/hooks_d3d.cpp: call-counting wrappers (HC09_TRACE_D3D=1) around every
function of the game's statically linked Xbox D3D that game code calls directly — the API
surface a native renderer has to replace (docs/NATIVE_RENDERER.md).

Usage: py -3.11 tools/gen_d3d_hooks.py   (run from the repo root, after build.sh/build.py)

D3D occupies 0x82320000-0x8233DBB8 (the Vd* kernel calls, D3D's GPU register dump strings
and PIX, the draw functions up to 0x8233DBB8; XAudio follows). Selected: functions in that range that some
function outside it calls with bl/b (ppcxref's index; nothing reaches D3D through stored
function pointers). Functions already wrapped by another hooks_*.cpp are skipped (one
strong definition per symbol); they are listed in the output's header.

Output: the first call of each function (swap, thread, r3-r6, caller), and every 5 s the
calls per frame of every active function with its three busiest callers.
HC09_TRACE_D3D=time adds the time spent in D3D: each thread's outermost D3D call (inclusive;
D3D calling itself is not counted twice), ms per frame by function. The wrappers in
hooks_native.cpp (draws, clears, resolves, swap...) include the native front end's time
(HC09_NATIVE_PROF reports that apart).
"""
import glob, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ppcxref  # noqa: E402

LO, HI = 0x82320000, 0x8233DBB8
refs, calls, callees = ppcxref.index()
api = set()
for f, cs in callees.items():
    if LO <= f < HI:
        continue
    api |= {c for c in cs if LO <= c < HI}
taken = set()
for f in glob.glob('runtime/hooks_*.cpp'):
    if f.replace('\\', '/').endswith('hooks_d3d.cpp'):
        continue
    taken |= {int(a, 16) for a in re.findall(r'PPC_FUNC\(sub_([0-9A-F]{8})\)', open(f, encoding='utf-8', errors='replace').read())}
skipped = sorted(api & taken)
traced = sorted(api)   # skipped ones are counted by their own wrapper through D3DTraceCount

out = [
    '// AUTO-GENERATED by tools/gen_d3d_hooks.py — diagnostic (HC09_TRACE_D3D=1).',
    '// Call counts of the D3D functions the game calls directly (its D3D API surface).',
    '// Wrapped elsewhere (counted through D3DTraceCount): ' + (' '.join('%08X' % a for a in skipped) or 'none'),
    '#include "kernel.h"', '#include "gpu.h"', '',
    '#include <algorithm>', '#include <atomic>', '#include <chrono>', '#include <cstdio>',
    '#include <cstdlib>', '#include <cstring>', '#include <mutex>', '#include <thread>', '#include <vector>', '',
    'namespace {',
    f'constexpr int kCount = {len(traced)};',
    'const uint32_t kAddr[kCount] = {',
]
for i in range(0, len(traced), 8):
    out.append('    ' + ', '.join('0x%08X' % a for a in traced[i:i + 8]) + ',')
out += [
    '};',
    'constexpr int kSlots = 8;   // callers remembered per function',
    'struct Stat',
    '{',
    '    std::atomic<uint64_t> calls{ 0 };',
    '    std::atomic<uint64_t> ns{ 0 };   // HC09_TRACE_D3D=time: inclusive time of outermost calls',
    '    std::atomic<uint32_t> lr[kSlots];',
    '    std::atomic<uint64_t> lrCalls[kSlots];',
    '};',
    'Stat g_stat[kCount];',
    'thread_local uint64_t t_enterNs = 0;   // D3DTraceEnter: when the outermost call started',
    'bool D3DTraceOn() { static const bool on = getenv("HC09_TRACE_D3D") != nullptr; return on; }',
    'bool D3DTimeOn() { static const bool on = [] { const char* e = getenv("HC09_TRACE_D3D"); return e && !strcmp(e, "time"); }(); return on; }',
    'thread_local int t_depth = 0;',
    'void Reporter()',
    '{',
    '    std::vector<uint64_t> last(kCount, 0), lastNs(kCount, 0);',
    '    std::vector<uint64_t> lastLr(kCount * kSlots, 0);',
    '    uint64_t sw0 = GpuSwapCount();',
    '    for (;;)',
    '    {',
    '        std::this_thread::sleep_for(std::chrono::seconds(5));',
    '        uint64_t sw = GpuSwapCount(), frames = std::max<uint64_t>(sw - sw0, 1);',
    '        sw0 = sw;',
    '        std::vector<std::pair<uint64_t, int>> d;',
    '        for (int i = 0; i < kCount; ++i)',
    '        {',
    '            uint64_t c = g_stat[i].calls.load(std::memory_order_relaxed);',
    '            if (c != last[i]) d.push_back({ c - last[i], i });',
    '            last[i] = c;',
    '        }',
    '        if (D3DTimeOn())',
    '        {',
    '            std::vector<std::pair<uint64_t, int>> t;',
    '            uint64_t total = 0;',
    '            for (int i = 0; i < kCount; ++i)',
    '            {',
    '                uint64_t c = g_stat[i].ns.load(std::memory_order_relaxed);',
    '                if (c != lastNs[i]) { t.push_back({ c - lastNs[i], i }); total += c - lastNs[i]; }',
    '                lastNs[i] = c;',
    '            }',
    '            std::sort(t.rbegin(), t.rend());',
    '            char buf[400] = "";',
    '            int o = 0;',
    '            for (size_t k = 0; k < t.size() && k < 10 && o < 360; ++k)',
    '                o += snprintf(buf + o, sizeof(buf) - o, " %08X:%.2f", kAddr[t[k].second], 1e-6 * double(t[k].first) / frames);',
    '            fprintf(stderr, "[d3d] time sw%llu: %.2f ms/frame in D3D (outermost calls, all threads); by function:%s\\n",',
    '                    (unsigned long long)sw, 1e-6 * double(total) / frames, buf);',
    '        }',
    '        if (d.empty()) continue;',
    '        std::sort(d.rbegin(), d.rend());',
    '        fprintf(stderr, "[d3d] report sw%llu: %zu functions active over %llu frames (calls/frame, top callers)\\n",',
    '                (unsigned long long)sw, d.size(), (unsigned long long)frames);',
    '        for (auto [n, i] : d)',
    '        {',
    '            std::vector<std::pair<uint64_t, uint32_t>> who;',
    '            for (int s = 0; s < kSlots; ++s)',
    '            {',
    '                uint64_t c = g_stat[i].lrCalls[s].load(std::memory_order_relaxed);',
    '                if (c != lastLr[i * kSlots + s]) who.push_back({ c - lastLr[i * kSlots + s], g_stat[i].lr[s].load() });',
    '                lastLr[i * kSlots + s] = c;',
    '            }',
    '            std::sort(who.rbegin(), who.rend());',
    '            char buf[160] = "";',
    '            int o = 0;',
    '            for (size_t k = 0; k < who.size() && k < 3; ++k)',
    '                o += snprintf(buf + o, sizeof(buf) - o, " %08X:%.1f", who[k].second, double(who[k].first) / frames);',
    '            fprintf(stderr, "[d3d]   sub_%08X %9.2f %s\\n", kAddr[i], double(n) / frames, buf);',
    '        }',
    '    }',
    '}',
    'inline void Count(int i, PPCContext& ctx)',
    '{',
    '    if (!D3DTraceOn()) return;',
    '    static std::once_flag once;',
    '    std::call_once(once, [] { std::thread(Reporter).detach(); });',
    '    Stat& s = g_stat[i];',
    '    if (s.calls.fetch_add(1, std::memory_order_relaxed) == 0)',
    '        fprintf(stderr, "[d3d] first sub_%08X sw%llu t%llu r3=%08X r4=%08X r5=%08X r6=%08X lr=%08X\\n", kAddr[i],',
    '                (unsigned long long)GpuSwapCount(), (unsigned long long)KernelCurrentTid(),',
    '                ctx.r3.u32, ctx.r4.u32, ctx.r5.u32, ctx.r6.u32, uint32_t(ctx.lr));',
    '    uint32_t lr = uint32_t(ctx.lr);',
    '    for (int k = 0; k < kSlots; ++k)',
    '    {',
    '        uint32_t cur = s.lr[k].load(std::memory_order_relaxed);',
    '        if (cur == 0 && s.lr[k].compare_exchange_strong(cur, lr)) cur = lr;',
    '        if (cur == lr) { s.lrCalls[k].fetch_add(1, std::memory_order_relaxed); return; }',
    '    }',
    '}',
    '// Timing scope of a wrapper (HC09_TRACE_D3D=time): the outermost call per thread.',
    'struct Scope',
    '{',
    '    int i;',
    '    std::chrono::steady_clock::time_point t0;',
    '    bool timed = false;',
    '    Scope(int k, PPCContext& ctx) : i(k)',
    '    {',
    '        Count(k, ctx);',
    '        if (D3DTimeOn() && t_depth++ == 0) { timed = true; t0 = std::chrono::steady_clock::now(); }',
    '    }',
    '    ~Scope()',
    '    {',
    '        if (!D3DTimeOn()) return;',
    '        --t_depth;',
    '        if (timed)',
    '            g_stat[i].ns.fetch_add(uint64_t(std::chrono::duration_cast<std::chrono::nanoseconds>(std::chrono::steady_clock::now() - t0).count()),',
    '                                   std::memory_order_relaxed);',
    '    }',
    '};',
    '}  // namespace', '',
]
out += [
    '// For wrappers in other files (hooks_native.cpp): count a call of `addr`.',
    'void D3DTraceCount(uint32_t addr, PPCContext& ctx)',
    '{',
    '    if (!D3DTraceOn()) return;',
    '    const uint32_t* p = std::lower_bound(kAddr, kAddr + kCount, addr);',
    '    if (p != kAddr + kCount && *p == addr) Count(int(p - kAddr), ctx);',
    '}',
    '// ... and time it (HC09_TRACE_D3D=time): call at entry, D3DTraceLeave with the result at exit.',
    'int D3DTraceEnter(uint32_t addr, PPCContext& ctx)',
    '{',
    '    if (!D3DTraceOn()) return -1;',
    '    const uint32_t* p = std::lower_bound(kAddr, kAddr + kCount, addr);',
    '    if (p == kAddr + kCount || *p != addr) return -1;',
    '    int i = int(p - kAddr);',
    '    Count(i, ctx);',
    '    if (!D3DTimeOn() || t_depth++ != 0) return D3DTimeOn() ? -2 : -1;',
    '    t_enterNs = uint64_t(std::chrono::duration_cast<std::chrono::nanoseconds>(std::chrono::steady_clock::now().time_since_epoch()).count());',
    '    return i;',
    '}',
    'void D3DTraceLeave(int token)',
    '{',
    '    if (token == -1) return;',
    '    --t_depth;',
    '    if (token < 0) return;',
    '    uint64_t now = uint64_t(std::chrono::duration_cast<std::chrono::nanoseconds>(std::chrono::steady_clock::now().time_since_epoch()).count());',
    '    g_stat[token].ns.fetch_add(now - t_enterNs, std::memory_order_relaxed);',
    '}', '',
]
for i, a in enumerate(traced):
    if a in taken:
        continue
    h = '%08X' % a
    out.append(f'extern "C" PPC_FUNC(__imp__sub_{h});')
    out.append(f'PPC_FUNC(sub_{h}) {{ Scope s({i}, ctx); __imp__sub_{h}(ctx, base); }}')
open('runtime/hooks_d3d.cpp', 'w', newline='\n').write('\n'.join(out) + '\n')
print(f'gen_d3d_hooks: {len(traced)} functions, {len(skipped)} wrapped elsewhere')
